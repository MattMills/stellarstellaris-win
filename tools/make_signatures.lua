-- make_signatures.lua : writes lua/stellar/signatures.lua, the stellar-fnmatch signatures of the
-- functions in lua/stellar/targets.lua and lua/stellar/functions.lua, taken from the .sig files
-- of reference (PDB) builds.
--
-- Usage: luajit tools/make_signatures.lua <out.lua> <newest.sig> [<older.sig> ...]
-- The fnmatch module (lua_fnmatch) must be on package.cpath (LUA_CPATH).
--
-- For each target and each reference build that has the function, its signatures (all unique in
-- that build) become alternatives: the most reliable kinds first, without the kinds that often
-- point at another function in the next patch (imm, a_vtslot, a_table_*, measured on 4.5.1 to
-- 4.5.2, see lua_fnmatch's README), at most MAX per build. Signatures a newer build already gave
-- are not repeated. Overloads (several functions with one name) are matched by address order.

local MAX = 64

-- most reliable first; kinds not listed are left out
local ORDER = {
    "str", "strset", "istr", "const", "imports", "export",
    "mnem", "bagcfg", "unwind", "callee_shapes", "caller_shapes", "wl1", "layout3",
    "a_callee_ord", "a_callset", "a_callee_pair", "a_global", "a_fnptr", "a_thunk",
    "exact", "pic", "block", "a_caller", "a_layout_prev", "a_layout_next",
    -- symbol relations resolve once the neighbour they name was found
    "s_callee_ord", "s_caller", "s_callset", "s_callee_pair", "s_thunk", "s_global", "s_fnptr",
    "s_layout_prev", "s_layout_next",
}
local RANK = {}
for i, k in ipairs(ORDER) do
    RANK[k] = i
end

local out_path = arg[1]
if out_path == nil or arg[2] == nil then
    io.stderr:write("usage: luajit make_signatures.lua <out.lua> <newest.sig> [<older.sig> ...]\n")
    os.exit(2)
end

local here = (arg[0]:match("^(.*)[/\\]") or ".")
package.path = here .. "/../lua/?.lua;" .. package.path
local fnmatch = require("fnmatch")
local targets = {}
for _, list in ipairs({ require("stellar.targets"), require("stellar.functions") }) do
    for _, t in ipairs(list) do
        targets[#targets + 1] = t
    end
end

local references = {}
for i = 2, #arg do
    local sf = assert(fnmatch.sig_file(arg[i]))
    references[#references + 1] = { sf = sf, path = arg[i] }
end

local function sorted_signatures(sf, rva)
    local sigs = {}
    for _, sig in ipairs(sf:signatures(rva)) do
        local rank = RANK[fnmatch.signature.kind(sig)]
        if rank then
            sigs[#sigs + 1] = { sig = sig, rank = rank }
        end
    end
    table.sort(sigs, function(a, b)
        if a.rank ~= b.rank then
            return a.rank < b.rank
        end
        return a.sig < b.sig
    end)
    return sigs
end

local function quote(s)
    return string.format("%q", s)
end

local lines = {
    "-- signatures.lua : stellar-fnmatch signatures of the functions in targets.lua and functions.lua.",
    "-- Generated by tools/make_signatures.lua from " .. #references .. " reference build(s), do not edit.",
    "--",
    "-- functions[name][overload] = list of { reference = i, rva = function rva in that build, signatures }",
    "",
    "return {",
    "    references = {",
}
for _, r in ipairs(references) do
    local sf = r.sf
    lines[#lines + 1] = string.format("        { id = %s, version = %s, build = %s, md5 = %s },",
        quote(sf:id()), quote(sf:version()), quote(sf:build_string()), quote(sf:md5()))
end
lines[#lines + 1] = "    },"
lines[#lines + 1] = "    functions = {"

local seen_names = {}
local summary = {}
for _, t in ipairs(targets) do
    if not seen_names[t.name] then
        seen_names[t.name] = true
        lines[#lines + 1] = string.format("        [%s] = {", quote(t.name))
        local overloads = {}
        local given = {}
        for ri, r in ipairs(references) do
            local functions = r.sf:functions_named(t.name)
            table.sort(functions, function(a, b) return a.rva < b.rva end)
            for k, f in ipairs(functions) do
                given[k] = given[k] or {}
                local list = {}
                for _, s in ipairs(sorted_signatures(r.sf, f.rva)) do
                    if #list >= MAX then
                        break
                    end
                    if not given[k][s.sig] then
                        given[k][s.sig] = true
                        list[#list + 1] = s.sig
                    end
                end
                overloads[k] = overloads[k] or {}
                overloads[k][#overloads[k] + 1] = { reference = ri, rva = f.rva, signatures = list }
            end
        end
        local counts = {}
        for k, from in ipairs(overloads) do
            lines[#lines + 1] = string.format("            { -- overload %d", k)
            local n = 0
            for _, e in ipairs(from) do
                n = n + #e.signatures
                lines[#lines + 1] = string.format("                { reference = %d, rva = 0x%x, signatures = {", e.reference, e.rva)
                for i = 1, #e.signatures, 4 do
                    local row = {}
                    for j = i, math.min(i + 3, #e.signatures) do
                        row[#row + 1] = quote(e.signatures[j])
                    end
                    lines[#lines + 1] = "                    " .. table.concat(row, ", ") .. ","
                end
                lines[#lines + 1] = "                } },"
            end
            lines[#lines + 1] = "            },"
            counts[#counts + 1] = n
        end
        lines[#lines + 1] = "        },"
        summary[#summary + 1] = string.format("%-60s %s", t.name:sub(1, 60), #counts == 0 and "not in any reference" or table.concat(counts, " + ") .. " signatures")
    end
end
lines[#lines + 1] = "    },"
lines[#lines + 1] = "}"

local f = assert(io.open(out_path, "wb"))
f:write(table.concat(lines, "\n"), "\n")
f:close()
for _, s in ipairs(summary) do
    print(s)
end
print("wrote " .. out_path)
